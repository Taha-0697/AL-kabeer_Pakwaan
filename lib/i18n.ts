export type Language = 'en' | 'ur';
export type TranslationKey = keyof typeof translations['en'];

let currentLang: Language = 'en';
let dynamicTranslations: Record<string, Record<string, string>> = { en: {}, ur: {} };

export const setLanguage = (lang: Language) => {
  currentLang = lang;
};

export const setDynamicTranslations = (custom: { key: string; en: string; ur: string }[]) => {
  custom.forEach(({ key, en, ur }) => {
    dynamicTranslations.en[key] = en;
    dynamicTranslations.ur[key] = ur;
  });
};

export const t = (key: TranslationKey | string): string => {
  if (dynamicTranslations[currentLang]?.[key]) {
    return dynamicTranslations[currentLang][key];
  }
  const dictKey = key as TranslationKey;
  return translations[currentLang]?.[dictKey] || translations['en']?.[dictKey] || (key as string);
};
